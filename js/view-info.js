// ============================================================
// namespace LuminariesApplication 情報表示管理
// ============================================================
const LuminariesApplication_ViewInfo = (() => {

	// ============================================================
	// class 情報表示管理（スマホ用クリック表示）
	// ============================================================
	class 情報表示管理 {

		// <summary>クリックされた人物の情報をテーブル表示する</summary>
		static 表示する(項目) {
			try {
				const コンテナ = document.getElementById("情報テーブルコンテナ");
				if (コンテナ == null) return;

				const テーブル = document.createElement("table");
				テーブル.id = "情報テーブル";

				// ============================================================
				// 種類ごとに項目名を切り替える
				// ============================================================
				let 行一覧 = [];

				if (項目.種類 == "恒星") {
					行一覧 = [
						["記号", 項目.記号],
						["名前", 項目.名前],
						["職業", 項目.職業または影響],
						["星座名", 項目.星座または惑星名],
						["ハウス", 項目.章位置 || "未入力"],
						["詳細データ", 項目.詳細データ || "未入力"]
					];
				}
				else if (項目.種類 == "惑星") {
					行一覧 = [
						["記号", 項目.記号],
						["名前", 項目.名前],
						["影響", 項目.職業または影響],
						["惑星名", 項目.星座または惑星名],
						["章位置", 項目.章位置 || "未入力"],
						["詳細データ", 項目.詳細データ || "未入力"]
					];
				}
				else if (項目.種類 == "地球") {
					行一覧 = [
						["記号", 項目.記号],
						["名前", 項目.名前],
						["影響", 項目.職業または影響],
						["地球", 項目.星座または惑星名],
						["詳細データ", 項目.詳細データ || "未入力"]
					];
				}
				else {
					行一覧 = [
						["記号", 項目.記号],
						["名前", 項目.名前],
						["職業または影響", 項目.職業または影響],
						["星座または惑星名", 項目.星座または惑星名],
						["章位置", 項目.章位置 || "未入力"],
						["詳細データ", 項目.詳細データ || "未入力"]
					];
				}

				// ============================================================
				// テーブル生成
				// ============================================================
				for (const [名称, 値] of 行一覧) {
					const tr = document.createElement("tr");

					const td1 = document.createElement("td");
					td1.textContent = 名称;

					const td2 = document.createElement("td");
					td2.textContent = 値;

					tr.appendChild(td1);
					tr.appendChild(td2);
					テーブル.appendChild(tr);
				}

				コンテナ.innerHTML = "";
				コンテナ.appendChild(テーブル);

			} catch (例外) {
				console.error("情報表示例外: ", 例外);
			}
		}
	}

	return {
		情報表示管理
	};

})();
