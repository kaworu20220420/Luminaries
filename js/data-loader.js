// ============================================================
// namespace LuminariesApplication データ読込管理
// ============================================================
const LuminariesApplication_DataLoader = (() => {

	// ============================================================
	// class データ読込管理
	// ============================================================
	class データ読込管理 {

		// <summary>TSVを読み込み配列に変換する</summary>
		static 読み込む(tsv内容) {
			try {
				if (tsv内容 == null) {
					console.error("TSV内容がnullです");
					return [];
				}

				const 行一覧 = tsv内容.split("\n");
				const 結果一覧 = [];

				for (const 行 of 行一覧) {
					if (行.trim() == "") continue;

					const 列 = 行.split("\t").map(x => x.trim());
					if (列.length < 2) {
						console.warn("列数不足: " + 行);
						continue;
					}

					const 記号 = 列[0];
					const 種類 = データ読込管理.種類判定(記号);

					// ============================================================
					// 種類ごとに列の意味を変える
					// ============================================================
					let 名前 = "";
					let 職業または影響 = "";
					let 星座または惑星名 = "";
					let 章位置 = "";
					let 詳細データ = "";

					// ---------------------------
					// 恒星（Star）
					// ---------------------------
					if (種類 == "恒星") {
						// 記号 / 名前 / 職業 / 星座名 / 場所 / 詳細データ
						名前 = 列[1] || "";
						職業または影響 = 列[2] || "";
						星座または惑星名 = 列[3] || "";
						章位置 = 列[4] || "";
						詳細データ = 列[5] || "";
					}

					// ---------------------------
					// 惑星（Planet）
					// ---------------------------
					else if (種類 == "惑星") {
						// 記号 / 名前 / 影響 / 惑星名 / 章位置 / 詳細データ
						名前 = 列[1] || "";
						職業または影響 = 列[2] || "";
						星座または惑星名 = 列[3] || "";
						章位置 = 列[4] || "";
						詳細データ = 列[5] || "";
					}

					// ---------------------------
					// 地球（Earth）
					// ---------------------------
					else if (種類 == "地球") {
						// 記号 / 名前 / 影響 / 地球
						名前 = 列[1] || "";
						職業または影響 = 列[2] || "";
						星座または惑星名 = 列[3] || "";
						詳細データ = 列[4] || "";
					}

					// ---------------------------
					// 不明（その他）
					// ---------------------------
					else {
						名前 = 列[1] || "";
						職業または影響 = 列[2] || "";
						星座または惑星名 = 列[3] || "";
						章位置 = 列[4] || "";
						詳細データ = 列[5] || "";
					}

					結果一覧.push({
						種類,
						記号,
						名前,
						職業または影響,
						星座または惑星名,
						章位置,
						詳細データ
					});
				}

				return 結果一覧;

			} catch (例外) {
				console.error("TSV読込例外: ", 例外);
				return [];
			}
		}

		// <summary>記号から種類を判定する</summary>
		static 種類判定(記号) {
			const 恒星記号一覧 = ["♈", "♉", "♊", "♋", "♌", "♍", "♎", "♏", "♐", "♑", "♒", "♓"];
			const 惑星記号一覧 = ["☿", "♀", "♂", "♃", "♄", "☽", "☉"];
			const 地球記号一覧 = ["⊕"];

			if (恒星記号一覧.includes(記号)) return "恒星";
			if (惑星記号一覧.includes(記号)) return "惑星";
			if (地球記号一覧.includes(記号)) return "地球";
			return "不明";
		}
	}

	return {
		データ読込管理
	};

})();
